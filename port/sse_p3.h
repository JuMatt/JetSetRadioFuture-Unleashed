static inline uint32_t p3_rcp_bits(uint32_t x)
{
    uint32_t s = x & 0x80000000u, e = (x >> 23) & 0xFF, m = x & 0x7FFFFF;
    int oe;
    if (e == 0xFF) return m ? (x | 0x400000u) : s;      /* NaN quieted, inf -> 0 */
    if (e == 0) return s | 0x7F800000u;                  /* 0 and denormals -> inf */
    oe = 253 - (int)e;
    if (oe <= 0) return s;                               /* result would be denormal */
    return s | ((uint32_t)oe << 23) | ((uint32_t)s_p3_rcp[m >> 12] << 11);
}
static inline uint32_t p3_rsq_bits(uint32_t x)
{
    uint32_t s = x & 0x80000000u, e = (x >> 23) & 0xFF, m = x & 0x7FFFFF;
    int u, odd, k;
    if (e == 0xFF) { if (m) return x | 0x400000u; return s ? 0xFFC00000u : 0; }
    if (e == 0) return s | 0x7F800000u;                  /* +-0 and denormals -> +-inf */
    if (s) return 0xFFC00000u;                           /* negative -> default NaN */
    u = (int)e - 127;
    odd = u & 1;
    k = (u - odd) / 2;
    return ((uint32_t)(126 - k) << 23) | ((uint32_t)s_p3_rsq[odd * 1024 + (m >> 13)] << 11);
}
